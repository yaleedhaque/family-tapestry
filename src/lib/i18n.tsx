const DICTS: Record<Lang, Dict> = { en, bn, hi, ar };

interface LangContextValue {
  lang: Lang;
  t: (key: string, ...args: string[]) => string;
  setLang: (l: Lang) => void;
  rtl: boolean;
}

const LangContext = createContext<LangContextValue>({
  lang: "en",
  t: (k) => en[k] ?? k,
  setLang: () => {},
  rtl: false,
});

export function useLang() {
  return useContext(LangContext);
}

const STORAGE_KEY = "family-tapestry-lang";

export default function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && ["en", "bn", "hi", "ar"].includes(saved)) setLangState(saved);
    setMounted(true);
  }, []);

  useEffect(() => {
    if (!mounted) return;
    const rtl = lang === AR;
    document.documentElement.lang = lang;
    document.documentElement.dir = rtl ? "rtl" : "ltr";
    localStorage.setItem(STORAGE_KEY, lang);
  }, [lang, mounted]);

  const t = (key: string, ...args: string[]) => {
    const template = DICTS[lang][key] ?? DICTS.en[key] ?? key;
    return args.reduce((str, arg, i) => str.split(`{${i}}`).join(arg), template);
  };

  const setLang = (l: Lang) => setLangState(l);

  return (
    <LangContext.Provider value={{ lang, t, setLang, rtl: isRtl(lang) }}>
      {children}
    </LangContext.Provider>
  );
}
